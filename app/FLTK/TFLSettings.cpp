// A name that no machine has yet: "Newton", "Newton 2", ...
static std::string
UniqueName(TFLSettings* inSettings, const std::string& inBase)
{
	for (int n = 1;; n++)
	{
		std::string theName = (n == 1) ? inBase : inBase + " " + std::to_string(n);
		bool taken = false;
		for (auto* machine : inSettings->mMachines)
			taken = taken || (theName == machine->GetName());
		if (!taken)
			return theName;
	}
}

// The files that make up a ROM image, see TROMImage::LoadROMAndREX(): the
// image, the Newton REx next to an .aif image or a "Senior Cirrus" image, and
// Einstein.rex next to it if the built-in one is not used.
static std::vector<std::string>
ROMFiles(const std::string& inPath, bool inBuiltinRex)
{
	std::vector<std::string> theFiles { inPath };
	const char* ext = fl_filename_ext(inPath.c_str());
	const char* name = fl_filename_name(inPath.c_str());
	if (ext && strcasecmp(ext, ".aif") == 0)
	{
		char theREX[FL_PATH_MAX];
		strncpy(theREX, inPath.c_str(), FL_PATH_MAX - 1);
		theREX[FL_PATH_MAX - 1] = 0;
		fl_filename_setext(theREX, FL_PATH_MAX, ".rex");
		theFiles.push_back(theREX);
	} else if (name && (strncmp(name, "Senior Cirrus", 13) == 0 || strncmp(name, "Senior DCirrus", 14) == 0)
		&& strstr(name, "image"))
	{
		std::string theHigh = inPath;
		theHigh.replace(theHigh.rfind("image"), 5, "high");
		theFiles.push_back(theHigh);
	}
	if (!inBuiltinRex)
	{
		char theREX[FL_PATH_MAX];
		strncpy(theREX, inPath.c_str(), FL_PATH_MAX - 1);
		theREX[FL_PATH_MAX - 1] = 0;
		char* theName = (char*) fl_filename_name(theREX);
		if (theName)
		{
			strcpy(theName, "Einstein.rex");
			theFiles.push_back(theREX);
		}
	}
	return theFiles;
}

// Copy a file. \return false if it can't be read or written.
static bool
CopyFile(const char* inFrom, const char* inTo)
{
	FILE* theFrom = fopen(inFrom, "rb");
	if (!theFrom)
		return false;
	FILE* theTo = fopen(inTo, "wb");
	if (!theTo)
	{
		fclose(theFrom);
		return false;
	}
	char buf[65536];
	size_t n;
	bool ok = true;
	while ((n = fread(buf, 1, sizeof(buf), theFrom)) > 0)
		ok = ok && (fwrite(buf, 1, n, theTo) == n);
	fclose(theFrom);
	ok = (fclose(theTo) == 0) && ok;
	return ok;
}

