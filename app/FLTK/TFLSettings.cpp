void
TFLMachineSettings::Load(Fl_Preferences& inPrefs, const char* inAppPath, const char* inUserDataPath, bool inOldKeys)
{
	char buf[FL_PATH_MAX];

	// ROM Preferences
	Fl_Preferences rom(inPrefs, "ROM");
	{
		snprintf(buf, sizeof(buf), "%s717006", inAppPath);
		LoadFile(rom, buf, inOldKeys, mROMInFolder, mROMName, mROMHostPath);
		rom.get("builtInRex", mUseBuiltinRex, true);
		rom.get("ID", mROMId, mROMId);
	}

	// Flash Preferences
	Fl_Preferences flash(inPrefs, "Flash");
	{
		snprintf(buf, sizeof(buf), "%sinternal.flash", inUserDataPath);
		LoadFile(flash, buf, inOldKeys, mFlashInFolder, mFlashName, mFlashHostPath);
	}

	// screen preferences
	Fl_Preferences screen(inPrefs, "Screen");
	{
		screen.get("width", screenWidth, 320);
		screen.get("height", screenHeight, 480);
		screen.get("scale", screenScale, 100);
		screen.get("fullScreen", fullScreen, 0);
		screen.get("AppWindowPosX", mAppWindowPosX, 150);
		screen.get("AppWindowPosY", mAppWindowPosY, 150);
		screen.get("Orientation", mScreenOrientation, -1);
		screen.get("OrientationROM", mScreenOrientationROM, -1);
		screen.get("ShowSpecialKeys", mShowSpecialKeys, 1);
	}

	// Memory preferences
	Fl_Preferences memory(inPrefs, "Memory");
	{
		memory.get("RAMSize", RAMSize, 64);
	}

	// system preferences
	Fl_Preferences newtSystem(inPrefs, "System");
	{
		newtSystem.get("FastStart", mFastStart, 1);
		char* theStatePath = nullptr;
		newtSystem.get("StatePath", theStatePath, "");
		SetStatePath(theStatePath);
		::free(theStatePath);
		char theID[32];
		snprintf(theID, sizeof(theID), "%04X%08X", (unsigned) mNewtonID[0], (unsigned) mNewtonID[1]);
		char* theStoredID = nullptr;
		newtSystem.get("NewtonID", theStoredID, theID);
		unsigned long long theValue = strtoull(theStoredID, nullptr, 16);
		::free(theStoredID);
		mNewtonID[0] = (KUInt32) ((theValue >> 32) & 0xFFFF);
		mNewtonID[1] = (KUInt32) (theValue & 0xFFFFFFFF);
	}

	// serial port preferences
	Fl_Preferences serial(inPrefs, "Serial");
	{
		serial.get("ExtrDriver", mExtrDriver, 4); // TSerialPorts::kTcpClientDriver
		::free(mExtrTcpServer);
		serial.get("ExtrTcpServer", mExtrTcpServer, "127.0.0.1");
		serial.get("ExtrTcpPort", mExtrTcpPort, 3679);
	}

	// the cards that stay in a slot (their UUIDs in the card list)
	Fl_Preferences pcmcia(inPrefs, "PCMCIA");
	for (int slot = 0; slot < 2; slot++)
	{
		char* theUUID = nullptr;
		pcmcia.get(slot == 0 ? "KeepInSlot0" : "KeepInSlot1", theUUID, mKeepInSlot[slot].c_str());
		mKeepInSlot[slot] = theUUID;
		::free(theUUID);
	}
}

void
TFLMachineSettings::Save(Fl_Preferences& inPrefs, bool inOldKeys) const
{
	// ROM Preferences
	Fl_Preferences rom(inPrefs, "ROM");
	{
		SaveFile(rom, inOldKeys, mROMInFolder, mROMName, mROMHostPath);
		rom.set("builtInRex", mUseBuiltinRex);
		rom.set("ID", mROMId);
	}

	// Flash Preferences
	Fl_Preferences flash(inPrefs, "Flash");
	{
		SaveFile(flash, inOldKeys, mFlashInFolder, mFlashName, mFlashHostPath);
	}

	// screen preferences
	Fl_Preferences screen(inPrefs, "Screen");
	{
		screen.set("width", screenWidth);
		screen.set("height", screenHeight);
		screen.set("scale", screenScale);
		screen.set("fullScreen", fullScreen);
		screen.set("AppWindowPosX", mAppWindowPosX);
		screen.set("AppWindowPosY", mAppWindowPosY);
		screen.set("Orientation", mScreenOrientation);
		screen.set("OrientationROM", mScreenOrientationROM);
		screen.set("ShowSpecialKeys", mShowSpecialKeys);
	}

	// Memory preferences
	Fl_Preferences memory(inPrefs, "Memory");
	{
		memory.set("RAMSize", RAMSize);
	}

	// system preferences
	Fl_Preferences newtSystem(inPrefs, "System");
	{
		newtSystem.set("FastStart", mFastStart);
		// An older Einstein only knows full paths.
		if (inOldKeys && mStatePath && mStatePath[0])
			newtSystem.set("StatePath", GetStatePath().c_str());
		else
			newtSystem.set("StatePath", mStatePath ? mStatePath : "");
		char theID[32];
		snprintf(theID, sizeof(theID), "%04X%08X", (unsigned) mNewtonID[0], (unsigned) mNewtonID[1]);
		newtSystem.set("NewtonID", theID);
	}

	// serial port preferences
	Fl_Preferences serial(inPrefs, "Serial");
	{
		serial.set("ExtrDriver", mExtrDriver);
		serial.set("ExtrTcpServer", mExtrTcpServer ? mExtrTcpServer : "");
		serial.set("ExtrTcpPort", mExtrTcpPort);
	}

	// the cards that stay in a slot
	Fl_Preferences pcmcia(inPrefs, "PCMCIA");
	pcmcia.set("KeepInSlot0", mKeepInSlot[0].c_str());
	pcmcia.set("KeepInSlot1", mKeepInSlot[1].c_str());
}

