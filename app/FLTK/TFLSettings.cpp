void
TFLSettings::StartMachine(TFLMachineSettings* inMachine)
{
	SelectMachine(inMachine);
	if (IsRunningElsewhere(inMachine))
	{
		fl_alert("\"%s\" already runs in another Einstein window.", inMachine->GetName());
		return;
	}
	if (!mRunningMode)
	{
		// Einstein just started: run it here, like the Start button.
		applyDialog();
		savePreferences();
		mSettingsPanel->hide();
	} else if (inMachine != mMachine)
	{
		// A machine runs here already: start another Einstein for this one.
		// It reads the settings from the file, so save them first.
		applyDialog();
		savePreferences();
		gApp->LaunchMachine(inMachine->GetUUID());
	}
}

/**
 Add a machine like the selected one: the same ROM, but its own flash, 4 MB of
 RAM and a new Newton ID.
 */
