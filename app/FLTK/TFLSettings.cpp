/**
 Read the machine list again from the preferences: another Einstein's Settings
 may have added, removed or moved machines since this one started, and
 machines that ran there saved their settings. Machines we know are reused,
 the one that runs here is not read again.
 */
void
TFLSettings::RefreshMachines()
{
	Fl_Preferences prefs(Fl_Preferences::USER, "robowerk.com", "einstein");
	Fl_Preferences machines(prefs, "Machines");
	char* theOrder = nullptr;
	machines.get("Order", theOrder, "");
	std::vector<TFLMachineSettings*> theList;
	for (char* uuid = strtok(theOrder, " "); uuid; uuid = strtok(nullptr, " "))
	{
		TFLMachineSettings* machine = nullptr;
		for (auto*& known : mMachines)
		{
			if (known && strcmp(known->GetUUID(), uuid) == 0)
			{
				machine = known;
				known = nullptr; // taken
				break;
			}
		}
		if (!machine)
			machine = new TFLMachineSettings(uuid, mUserDataPath.c_str());
		if (machine != mMachine)
			machine->LoadFromFolder(appPath);
		theList.push_back(machine);
	}
	::free(theOrder);
	// Machines that are gone from the list, except the one that runs here.
	for (auto* known : mMachines)
	{
		if (!known)
			continue;
		if (known == mMachine)
			theList.push_back(known);
		else
			delete known;
	}
	mMachines = theList;
	if (std::find(mMachines.begin(), mMachines.end(), mEditMachine) == mMachines.end())
		mEditMachine = mMachine;
	if (mMachineList)
		mMachineList->Update();
}

/**
 Save the machine that runs: its own file, and the old keys if it is the first
 machine in the list. The list is read from the file, because the Settings
 of another Einstein may have changed it since this one started.
 */
void
TFLSettings::SaveRunningMachine()
{
	if (!mMachine)
		return;
	mMachine->SaveToFolder();

	Fl_Preferences prefs(Fl_Preferences::USER, "robowerk.com", "einstein");
	Fl_Preferences machines(prefs, "Machines");
	char* theOrder = nullptr;
	machines.get("Order", theOrder, "");
	const char* theFirst = strtok(theOrder, " ");
	if (theFirst && strcmp(theFirst, mMachine->GetUUID()) == 0)
	{
		mMachine->Save(prefs, true);
		// The first machine's slots are also stored with each card, where an
		// older Einstein looks for them (and where LoadMachines() reads them).
		Fl_Preferences cardlist(prefs, "PCMCIA/CardList");
		for (auto* card : mCardList)
		{
			if (cardlist.groupExists(card->GetUUID()))
			{
				Fl_Preferences cardPrefs(cardlist, card->GetUUID());
				cardPrefs.set("keepInSlot", SlotKeepingCard(mMachine, card));
			}
		}
	}
	machines.set("LastUsed", mMachine->GetUUID());
	::free(theOrder);
}

