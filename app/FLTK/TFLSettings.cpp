/**
 Read the list of machines and their settings.

 The group Machines holds the UUIDs in the order of the list (Order, separated
 by spaces) and the machine that ran last (LastUsed). Each machine has its own
 folder with a Machine.prefs. The first start of this version finds no list
 and makes one machine from the settings in the old keys, which keeps its
 flash and state files where they are. The first machine is always also
 read from the old keys, where an older Einstein may have changed it.
 */
void
TFLSettings::LoadMachines(Fl_Preferences& inPrefs)
{
	for (auto* machine : mMachines)
		delete machine;
	mMachines.clear();
	mMachine = nullptr;

	Fl_Preferences machines(inPrefs, "Machines");
	char* theOrder = nullptr;
	char* theLastUsed = nullptr;
	machines.get("Order", theOrder, "");
	machines.get("LastUsed", theLastUsed, "");

	// strtok() changes the string, so work on our own copy
	for (char* uuid = strtok(theOrder, " "); uuid; uuid = strtok(nullptr, " "))
	{
		auto* machine = new TFLMachineSettings(uuid, mUserDataPath.c_str());
		machine->LoadFromFolder(appPath);
		mMachines.push_back(machine);
		if (strcmp(uuid, theLastUsed) == 0)
			mMachine = machine;
	}
	::free(theOrder);
	::free(theLastUsed);

	if (mMachines.empty())
	{
		// First start with machines: the settings so far become the first one.
		auto* machine = new TFLMachineSettings(Fl_Preferences::newUUID(), mUserDataPath.c_str());
		machine->Load(inPrefs, appPath, mUserDataPath.c_str());
		machine->SetName("Newton");
		// The default checkpoint now lives in the machine's folder. Keep
		// finding the one in the user data folder, if it was the last one.
		std::string theOldState = mUserDataPath + "Einstein.state";
		FILE* theFile = (machine->mStatePath && machine->mStatePath[0]) ? nullptr : fopen(theOldState.c_str(), "rb");
		if (theFile)
		{
			fclose(theFile);
			machine->SetStatePath(theOldState.c_str());
		}
		mMachines.push_back(machine);
		// Save the list now: a quitting Einstein only saves its own machine.
		mMachine = machine;
		SaveMachines(inPrefs);
	} else
	{
		// The first machine is also in the old keys, and an older Einstein may
		// have changed them since. Its changes win.
		mMachines[0]->Load(inPrefs, appPath, mMachines[0]->GetFolder().c_str());
	}
	if (!mMachine)
		mMachine = mMachines[0];
}

/**
 Write the list of machines and the settings of each one. The first machine
 also goes into the old keys, so an older Einstein launches it.
 */
void
TFLSettings::SaveMachines(Fl_Preferences& inPrefs)
{
	std::string theOrder;
	for (auto* machine : mMachines)
	{
		if (!theOrder.empty())
			theOrder += " ";
		theOrder += machine->GetUUID();
		// A machine that runs in another Einstein saves itself when it quits,
		// and our copy may be older.
		if (!IsRunningElsewhere(machine))
			machine->SaveToFolder();
	}
	Fl_Preferences machines(inPrefs, "Machines");
	machines.set("Order", theOrder.c_str());
	machines.set("LastUsed", mMachine ? mMachine->GetUUID() : "");

	if (!mMachines.empty() && !IsRunningElsewhere(mMachines[0]))
		mMachines[0]->Save(inPrefs);
}

/**
 Is this machine running in another Einstein process?
 */
bool
TFLSettings::IsRunningElsewhere(const TFLMachineSettings* inMachine) const
{
	// Our own lock also counts as "elsewhere" for the lock file, so leave out
	// the machine that this process runs.
	if (inMachine == mMachine)
		return false;
	return TFLFileLock::IsHeldElsewhere(inMachine->GetFolder() + "Machine.lock");
}

/**
 Save the machine that runs: its own file, and the old keys if it is the first
 machine in the list. The list is read from the file, because the Settings
 of another Einstein may have changed it since this one started.
 */
void
TFLSettings::SaveRunningMachine()
{
	if (!mMachine)
		return;
	mMachine->SaveToFolder();

	Fl_Preferences prefs(Fl_Preferences::USER, "robowerk.com", "einstein");
	Fl_Preferences machines(prefs, "Machines");
	char* theOrder = nullptr;
	machines.get("Order", theOrder, "");
	const char* theFirst = strtok(theOrder, " ");
	if (theFirst && strcmp(theFirst, mMachine->GetUUID()) == 0)
		mMachine->Save(prefs);
	machines.set("LastUsed", mMachine->GetUUID());
	::free(theOrder);
}

void
TFLSettings::loadPreferences()
{
	char buf[FL_PATH_MAX];

	Fl_Preferences prefs(Fl_Preferences::USER, "robowerk.com", "einstein");

	// general preferences
	prefs.get("dontShow", dontShow, 0);

	// the machines, see LoadMachines()
	buf[0] = 0;
	prefs.getUserdataPath(buf, FL_PATH_MAX - 15);
	mUserDataPath = buf;
	LoadMachines(prefs);

	// screen preferences
	Fl_Preferences screen(prefs, "Screen");
	{
		screen.get("hideMouse", hideMouse, 0);
		screen.get("AllowScreenResize", mAllowScreenResize, true);
		screen.get("AllowFullscreen", mAllowFullscreen, true);

		screen.get("LaunchMonitorAtBoot", mLaunchMonitorAtBoot, 0);
		screen.get("BreakAtROMBoot", mBreakAtROMBoot, 0);

#if TARGET_OS_MAC
		screen.get("ShowMenubar", mShowMenubar, 0);
#else
		screen.get("ShowMenubar", mShowMenubar, 1);
#endif
		screen.get("ShowToolbar", mShowToolbar, 1);
	}

	// --- PCMCIA Card settings
	Fl_Preferences pcmcia(prefs, "PCMCIA");

	// --- a list of known PCMCIA Cards
	Fl_Preferences cardlist(pcmcia, "CardList");

	Boolean networkCardFound = false;
	for (int i = 0; i < cardlist.groups(); i++)
	{
		Fl_Preferences cardprefs(cardlist, i);
		TFLPCCardSettings* card = new TFLPCCardSettings(cardprefs);
		mCardList.push_back(card);
		if (strcmp(cardprefs.name(), TFLPCCardSettings::kNetworkUUID) == 0)
		{
			networkCardFound = true;
			// fix a wrong entry, created by older version of Einstein.
			card->SetType(TFLPCCardSettings::CardType::kNetwork);
		}
	}
	if (!networkCardFound)
	{
		TFLPCCardSettings* card = new TFLPCCardSettings(TFLPCCardSettings::kNetworkUUID, "Einstein Network Card");
		card->SetType(TFLPCCardSettings::CardType::kNetwork);
		card->SetTag(">NET");
		mCardList.push_back(card);
	}

	// Newton Internet resources
	Fl_Preferences resources(prefs, "Resources");
	{
		resources.get("UnnaPath", mUnnaPath, "http://www.unna.org/");
		resources.get("MessagepadOrgPath", mMessagepadOrgPath, "http://www.messagepad.org/");
		resources.get("GitRepoPath", mGitRepoPath, "https://github.com/pguyot/Einstein.git");
		resources.get("DevArmAsm", mDevAsmPath, "/opt/homebrew/bin/arm-none-eabi-as");
		resources.get("DevArmObjCopy", mDevObjCopyPath, "/opt/homebrew/bin/arm-none-eabi-objcopy");
		resources.get("DevArmObjDump", mDevObjDumpPath, "/opt/homebrew/bin/arm-none-eabi-objdump");
	}
}

void
TFLSettings::savePreferences()
{
	Fl_Preferences prefs(Fl_Preferences::USER, "robowerk.com", "einstein");

	// general preferences
	prefs.set("dontShow", dontShow);

	// the machines, see SaveMachines()
	SaveMachines(prefs);

	// screen preferences
	Fl_Preferences screen(prefs, "Screen");
	{
		screen.set("hideMouse", hideMouse);
		screen.set("AllowScreenResize", mAllowScreenResize);
		screen.set("AllowFullscreen", mAllowFullscreen);

		screen.set("LaunchMonitorAtBoot", mLaunchMonitorAtBoot);
		screen.set("BreakAtROMBoot", mBreakAtROMBoot);

		screen.set("ShowMenubar", mShowMenubar);
		screen.set("ShowToolbar", mShowToolbar);
	}

	// --- PCMCIA Card settings
	Fl_Preferences pcmcia(prefs, "PCMCIA");

	// --- a list of known PCMCIA Cards
	Fl_Preferences cardlist(pcmcia, "CardList");
	cardlist.clear();

	for (size_t i = 0; i < mCardList.size(); i++)
	{
		TFLPCCardSettings* card = mCardList[i];
		Fl_Preferences cardPrefs(cardlist, card->GetUUID());
		card->WritePrefs(cardPrefs);
	}

	// Newton Internet resources
	Fl_Preferences resources(prefs, "Resources");
	{
		resources.set("UnnaPath", mUnnaPath);
		resources.set("MessagepadOrgPath", mMessagepadOrgPath);
		resources.set("GitRepoPath", mGitRepoPath);
		resources.set("DevArmAsm", mDevAsmPath);
		resources.set("DevArmObjCopy", mDevObjCopyPath);
		resources.set("DevArmObjDump", mDevObjDumpPath);
	}
}

const char*
TFLSettings::GetROMDetails(const char* inFilename)
{
	const int text_size = 2 * FL_PATH_MAX;
	static char* text = nullptr;
	if (!text)
	{
		text = (char*) malloc(text_size + 1);
	}

	mDialogROMId = -1;
	// Only to find out which ROM it is: no need to apply the patches.
	TROMImage* theROMImage = TROMImage::LoadROMAndREX(inFilename, true, true, false);
	if (!theROMImage)
	{
		strncpy(text, "Can't load ROM image.\nFile format not supported.", text_size);
		return text;
	}
	if (theROMImage->GetErrorCode() == TROMImage::kNoError)
	{
		mDialogROMId = theROMImage->GetROMId();
		switch (theROMImage->GetROMId())
		{
			case TROMImage::k717006:
				strncpy(text,
					"MessagePad MP2x00 US ROM\n"
					"ROM Version 2.1 (717006)-0",
					text_size);
				break;
			case TROMImage::kMP2x00DROM:
				strncpy(text,
					"MessagePad MP2x00 D ROM\n"
					"ROM Version D-2.1 (747129)-0",
					text_size);
				break;
			case TROMImage::kEMate300ROM:
				strncpy(text,
					"eMate 300 ROM\n"
					"ROM Version 2.2.00 (737041)",
					text_size);
				break;
			case TROMImage::kWatsonROM:
				strncpy(text,
					"Schlumberger Watson FR ROM\n"
					"ROM Version FR 2.2.00-0",
					text_size);
				break;
			default:
				strncpy(text,
					"Unknown ROM or not a ROM\n"
					"File content not recognized",
					text_size);
				break;
		}
		if (!theROMImage->CRCValid())
		{
			strncat(text, " *** PATCHED ***", text_size);
		}
	} else
	{
		switch (theROMImage->GetErrorCode())
		{
			case TROMImage::kErrorLoadingROMFile:
				snprintf(text, text_size,
					"Can't load ROM file\n%s",
					strerror(errno));
				break;
			case TROMImage::kErrorLoadingNewtonREXFile:
				snprintf(text, text_size,
					"Can't load Newton REX file\n%s",
					strerror(errno));
				break;
			case TROMImage::kErrorLoadingEinsteinREXFile:
				snprintf(text, text_size,
					"Can't load Einstein REX file\n%s",
					strerror(errno));
				break;
			case TROMImage::kErrorWrongSize:
				snprintf(text, text_size,
					"Can't load ROM file\nUnexpected file size.");
				break;
		}
	}
	delete theROMImage;
	return text;
}

