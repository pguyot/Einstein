/**
 \brief Carry out a menu choice (-1 means Cancel).
 */
void TSDLApp::HandleMenuChoice(int inMenuId, int inItem)
{
	if (inItem < 0) return; // Cancel
	static const char* kRestartNote =
		"This takes effect the next time Einstein starts.\n\n"
		"To restart now, close Einstein from the recent apps and open it again. "
		"NewtonOS boots normally then, with your data kept.";
	switch (inMenuId) {
		case kMenuMain:
			switch (inItem) {
				case kMenuPower:
					if (mPlatformManager) mPlatformManager->SendPowerSwitchEvent();
					break;
				case kMenuBacklight:
					if (mPlatformManager) mPlatformManager->SendBacklightEvent();
					break;
				case kMenuNetwork:
					SetNetworkCardInserted(!mNetworkCardInserted);
					break;
				case kMenuNetworkDriver:
					ShowNetworkSoftwareMenu();
					break;
				case kMenuInternetSetup:
					// As Install Essentials in the FLTK app. Does nothing if NIE
					// is not installed.
					if (mPlatformManager)
						mPlatformManager->EvalNewtonScript("GetRoot().|InternetSetup:NIE|:Open();");
					break;
				case kMenuStorageCards:
					ShowStorageCardsMenu();
					break;
				case kMenuInternalMemory:
					ShowInternalMemoryMenu();
					break;
				case kMenuReboot:
					if (mPlatformManager) mPlatformManager->EvalNewtonScript("Reboot();");
					break;
				case kMenuLog:
					mShowLog = !mShowLog;
					RedrawAll();
					break;
				case kMenuOpenSettings:
					ShowSettingsMenu();
					break;
			}
			break;
		case kMenuSettings:
			switch (inItem) {
				case kSettingRAM:
					ShowList(kMenuRAM, "Memory (RAM)",
							 std::vector<std::string>(std::begin(kRAMNames), std::end(kRAMNames)),
							 RAMChoiceIndex(mRAMPages));
					break;
				case kSettingScreen:
					ShowList(kMenuScreen, "Screen",
							 { "MessagePad size (320 x 480)", "Fit to the window" },
							 mAdjustToAspectRatio ? 1 : 0);
					break;
				case kSettingEmulatorLog:
					ShowList(kMenuEmulatorLog, "Detailed emulator log",
							 { "Off (faster)", "On: log every device access (for debugging, much slower)" },
							 mEmulatorLogEnabled ? 1 : 0);
					break;
				case kSettingFastStart:
					ShowList(kMenuFastStart, "Fast start",
							 { "On: continue where Einstein was", "Off: boot NewtonOS at every start" },
							 mFastStartEnabled ? 0 : 1);
					break;
			}
			break;
		case kMenuRAM:
			if (inItem < 4 && kRAMPages[inItem] != mRAMPages) {
				mRAMPages = kRAMPages[inItem];
				SaveSettings();
				SDL_ShowSimpleMessageBox(SDL_MESSAGEBOX_INFORMATION, "Memory", kRestartNote, mSDLWindow);
			}
			break;
		case kMenuScreen:
			if ((inItem == 1) != mAdjustToAspectRatio) {
				mAdjustToAspectRatio = mAdjustToScreenDPI = (inItem == 1);
				SaveSettings();
				SDL_ShowSimpleMessageBox(SDL_MESSAGEBOX_INFORMATION, "Screen", kRestartNote, mSDLWindow);
			}
			break;
		case kMenuFastStart:
			mFastStartEnabled = (inItem == 0);
			SaveSettings();
			break;
		case kMenuEmulatorLog:
			if ((inItem == 1) != mEmulatorLogEnabled) {
				mEmulatorLogEnabled = (inItem == 1);
				SaveSettings();
				SDL_ShowSimpleMessageBox(SDL_MESSAGEBOX_INFORMATION, "Detailed emulator log", kRestartNote, mSDLWindow);
			}
			break;
		case kMenuStorage: {
			size_t n = mCardMenuFiles.size();
			if ((size_t)inItem < n) {
				const std::string& file = mCardMenuFiles[inItem];
				if (mStorageCard && file == mStorageCardFile)
					RemoveStorageCard();
				else
					InsertStorageCard(file);
			} else if ((size_t)inItem == n) {
				ShowList(kMenuNewLinear, "New linear flash card",
						 { "2 MB", "4 MB", "8 MB", "16 MB", "32 MB" });
			} else if ((size_t)inItem == n + 1) {
				ShowList(kMenuNewATA, "New ATA flash card",
						 { "4 MB", "8 MB", "16 MB", "32 MB", "64 MB" });
			} else if ((size_t)inItem == n + 2) {
				InstallATASupport();
			} else if ((size_t)inItem == n + 3) {
				ChooseFile(kFileImportCard, false, nullptr);
			} else if ((size_t)inItem == n + 4 && n > 0) {
				ShowList(kMenuExportCard, "Export which card?", mCardMenuFiles);
			}
			break;
		}
		case kMenuNewLinear: {
			static const int kSizes[] = { 2, 4, 8, 16, 32 };
			if (inItem < 5) CreateStorageCard(false, kSizes[inItem]);
			break;
		}
		case kMenuNewATA: {
			static const int kSizes[] = { 4, 8, 16, 32, 64 };
			if (inItem < 5) CreateStorageCard(true, kSizes[inItem]);
			break;
		}
		case kMenuExportCard:
			if ((size_t)inItem < mCardMenuFiles.size()) {
				mCardToExport = mCardMenuFiles[inItem];
				if (mStorageCard && mCardToExport == mStorageCardFile) {
					SDL_ShowSimpleMessageBox(SDL_MESSAGEBOX_INFORMATION, "Export card",
						"Please remove the card first, so that all of its data is in the file.",
						mSDLWindow);
					break;
				}
				ChooseFile(kFileExportCard, true, mCardToExport.c_str());
			}
			break;
		case kMenuInternal:
			switch (inItem) {
				case 0:
					ChooseFile(kFileBackupFlash, true, "einstein.flash");
					break;
				case 1: {
					const SDL_MessageBoxButtonData buttons[] = {
						{ SDL_MESSAGEBOX_BUTTON_ESCAPEKEY_DEFAULT, 0, "Cancel" },
						{ 0, 1, "Choose backup" } };
					const SDL_MessageBoxData data { SDL_MESSAGEBOX_WARNING, mSDLWindow, "Restore",
						"Restoring replaces everything in the Newton's internal memory with the "
						"backup, the next time Einstein starts.", 2, buttons, nullptr };
					int answer = 0;
					if (SDL_ShowMessageBox(&data, &answer) && answer == 1)
						ChooseFile(kFileRestoreFlash, false, nullptr);
					break;
				}
				case 2: {
					const SDL_MessageBoxButtonData buttons[] = {
						{ SDL_MESSAGEBOX_BUTTON_ESCAPEKEY_DEFAULT, 0, "Cancel" },
						{ 0, 1, "Brain Wipe" } };
					const SDL_MessageBoxData data { SDL_MESSAGEBOX_WARNING, mSDLWindow, "Brain Wipe",
						"The Newton restarts and offers to erase all data in its internal memory "
						"(a Brain Wipe, as on a real MessagePad).", 2, buttons, nullptr };
					int answer = 0;
					if (SDL_ShowMessageBox(&data, &answer) && answer == 1 && mMonitor) {
						(void) ::remove(FastStartFilePath().string().c_str());
						if (!mMonitor->RequestReset(true))
							mLog->FLogLine("Brain Wipe: the monitor is busy, try again");
					}
					break;
				}
			}
			break;
		case kMenuNetSoftware: {
			// Paths on UNNA, as in the FLTK app's Install Essentials.
			static const char* kUNNA = "http://www.unna.org/";
			static const char* kSystemUpdates[] = {
				"unna/apple/software/SystemPatches/english/2x00/mp717260.pkg",	// MP2x00 US
				"unna/apple/software/SystemPatches/german/2x00/mp747260.pkg",	// MP2x00 German
				"unna/apple/software/SystemPatches/english/eMate/EM737246.PKG",	// eMate 300
				nullptr															// Watson: none
			};
			// The order matters: the Ethernet module (enetsup) registers with
			// the Internet Enabler (inetenbl) when it is installed, so the
			// enabler comes first; otherwise Internet Setup says there are
			// no module packages installed. This is the order of Matthias
			// Melcher's Einstein instructions; NE2K.pkg comes last.
			static const char* kNIE[] = {
				"unna/apple/software/Internet/NIE2/REGPKGS/inetenbl.pkg",	// Internet Enabler
				"unna/apple/software/Internet/NIE2/REGPKGS/inetstup.pkg",	// Internet Setup
				"unna/apple/software/Internet/NIE2/ENETSUP/newtdev.pkg",	// Newton Devices
				"unna/apple/software/Internet/NIE2/ENETSUP/enetsup.pkg"	// NIE Ethernet module
			};
			KSInt32 romId = mROMImage ? mROMImage->GetROMId() : -1;
			const char* update = (romId >= 0 && romId < 4) ? kSystemUpdates[romId] : nullptr;
			std::vector<std::string> list;
			bool withUpdate = (inItem == 0 || inItem == 3);
			if (withUpdate) {
				if (!update) {
					SDL_ShowSimpleMessageBox(SDL_MESSAGEBOX_INFORMATION, "System Update",
						"Apple did not release a System Update for this ROM.", mSDLWindow);
					if (inItem == 0) break;
				} else {
					const SDL_MessageBoxButtonData buttons[] = {
						{ SDL_MESSAGEBOX_BUTTON_ESCAPEKEY_DEFAULT, 0, "Cancel" },
						{ SDL_MESSAGEBOX_BUTTON_RETURNKEY_DEFAULT, 1, "Install" } };
					const SDL_MessageBoxData data { SDL_MESSAGEBOX_WARNING, mSDLWindow,
						"System Update",
						"Installing the System Update may erase all data on the Newton.\n\n"
						"Please proceed only if this is a new Newton, or if its data is backed up.",
						2, buttons, nullptr };
					int answer = 0;
					if (!SDL_ShowMessageBox(&data, &answer) || answer != 1) break;
					list.push_back(std::string(kUNNA) + update);
				}
			}
			if (inItem == 1 || inItem == 3)
				for (auto path : kNIE) list.push_back(std::string(kUNNA) + path);
			if (inItem == 2 || inItem == 3)
				list.push_back("einstein:NE2K.pkg"); // last: it needs the NIE packages
			if (!list.empty()) DownloadAndInstall(list);
			break;
		}
	}
}

