namespace {
	// One download, handed from the download thread to the SDL thread.
	struct SDownload {
		std::string fName;			// URL, or "einstein:NE2K.pkg"
		std::vector<KUInt8> fData;	// the package, empty for a built-in one
		std::string fError;			// empty if it worked
		bool fLast { false };		// the last one of the list
	};
}

/**
 \brief Download packages one after the other on a thread, and install them in
 the same order on the SDL thread (see HandleDownloadEvent()). Entries that
 start with "einstein:" are built into Einstein.
 */
void TSDLApp::DownloadAndInstall(const std::vector<std::string>& inPackages)
{
	if (mDownloading.exchange(true)) return;
	mDownloadStarted = SDL_GetTicks();
	if (mDownloadEventType == 0)
		mDownloadEventType = SDL_RegisterEvents(1);
	if (mDownloadEventType == 0) { mDownloading = false; return; }
	Uint32 eventType = mDownloadEventType;
	TLog* log = mLog;
	std::atomic<bool>* downloading = &mDownloading; // the app lives until the process ends
	std::thread([inPackages, eventType, log, downloading]() {
		for (size_t i = 0; i < inPackages.size(); ++i) {
			auto* item = new SDownload;
			item->fName = inPackages[i];
			item->fLast = (i + 1 == inPackages.size());
			if (item->fName.rfind("einstein:", 0) != 0) {
				log->FLogLine("Downloading %s (%u of %u)", item->fName.c_str(),
							  (unsigned)(i + 1), (unsigned)inPackages.size());
				if (item->fName.rfind("https://", 0) == 0) {
					// The C++ HTTP client has no https.
#if TARGET_OS_ANDROID
					std::vector<unsigned char> body;
					if (AndroidHttpGet(item->fName, body, item->fError))
						item->fData.assign(body.begin(), body.end());
#else
					item->fError = "https downloads are not supported here.";
#endif
				} else {
					try {
						http::Request request(item->fName);
						const http::Response response = request.send("GET");
						if (response.status == 404)
							item->fError = "File not found.";
						else if (response.status < 200 || response.status >= 300)
							item->fError = "The file can't be downloaded (status " + std::to_string(response.status) + ").";
						else
							item->fData.assign(response.body.begin(), response.body.end());
					} catch (const std::exception& e) {
						item->fError = e.what();
					}
				}
				if (item->fError.empty()
					&& (item->fData.size() < 7 || memcmp(item->fData.data(), "package", 7) != 0)) {
					item->fError = "This is not a Newton package.";
					item->fData.clear();
				}
			}
			bool failed = !item->fError.empty();
			SDL_Event event;
			SDL_zero(event);
			event.type = eventType;
			event.user.data1 = item;
			if (!SDL_PushEvent(&event)) {
				log->FLogLine("Can't hand over %s: %s", item->fName.c_str(), SDL_GetError());
				delete item;
				*downloading = false;
				break;
			}
			if (failed) break; // later packages may depend on this one
		}
	}).detach();
}

/**
 \brief Install a downloaded package, or report why it failed.
 */
void TSDLApp::HandleDownloadEvent(SDL_Event* inEvent)
{
	auto* item = static_cast<SDownload*>(inEvent->user.data1);
	if (!item) return;
	if (!item->fError.empty()) {
		mDownloading = false;
		mLog->FLogLine("Can't install %s: %s", item->fName.c_str(), item->fError.c_str());
		std::string text = "Can't install\n" + item->fName + "\n\n" + item->fError +
			"\n\nThe packages after it were not installed.";
		SDL_ShowSimpleMessageBox(SDL_MESSAGEBOX_WARNING, "Install packages", text.c_str(), mSDLWindow);
	} else if (mPlatformManager) {
		if (item->fName == "einstein:NE2K.pkg") {
			mLog->FLogLine("Installing the built-in NE2K.pkg (%u bytes)", gNE2KPackageSize);
			mPlatformManager->InstallPackage(gNE2KPackage, gNE2KPackageSize);
		} else {
			mLog->FLogLine("Installing %s (%u bytes)", item->fName.c_str(), (unsigned)item->fData.size());
			mPlatformManager->InstallPackage(item->fData.data(), (KUInt32)item->fData.size());
		}
	}
	if (item->fLast) mDownloading = false;
	delete item;
}

/**
 \brief Read the settings from Einstein.prefs (one "key=value" per line).
 Missing keys keep their defaults.
 */
void TSDLApp::LoadSettings()
{
	std::filesystem::path path = mPrivateDataPath / "Einstein.prefs";
	size_t size = 0;
	char* text = (char*)SDL_LoadFile(path.string().c_str(), &size);
	if (!text) return;
	std::string all(text, size);
	SDL_free(text);
	size_t pos = 0;
	while (pos < all.size()) {
		size_t eol = all.find('\n', pos);
		if (eol == std::string::npos) eol = all.size();
		std::string line = all.substr(pos, eol - pos);
		pos = eol + 1;
		size_t eq = line.find('=');
		if (eq == std::string::npos) continue;
		std::string key = line.substr(0, eq);
		int value = SDL_atoi(line.c_str() + eq + 1);
		if (key == "RAMPages") mRAMPages = kRAMPages[RAMChoiceIndex(value)];
		else if (key == "ScreenFit") mAdjustToAspectRatio = mAdjustToScreenDPI = (value != 0);
		else if (key == "FastStart") mFastStartEnabled = (value != 0);
		else if (key == "NetworkCard") mNetworkCardWanted = (value != 0);
		else if (key == "StorageCard") mStorageCardWanted = line.substr(eq + 1);
		else if (key == "EmulatorLog") mEmulatorLogEnabled = (value != 0);
	}
	mLog->FLogLine("Settings: RAM %d pages, screen %s, fast start %s, network card %s",
				   mRAMPages, mAdjustToAspectRatio ? "fit" : "320x480",
				   mFastStartEnabled ? "on" : "off", mNetworkCardWanted ? "in" : "out");
}

/**
 \brief Write the settings to Einstein.prefs.
 */
void TSDLApp::SaveSettings()
{
	SDL_CreateDirectory(mPrivateDataPath.string().c_str());
	std::filesystem::path path = mPrivateDataPath / "Einstein.prefs";
	char numbers[256];
	SDL_snprintf(numbers, sizeof(numbers), "RAMPages=%d\nScreenFit=%d\nFastStart=%d\nNetworkCard=%d\n",
				 mRAMPages, mAdjustToAspectRatio ? 1 : 0, mFastStartEnabled ? 1 : 0,
				 mNetworkCardWanted ? 1 : 0);
	std::string text = std::string(numbers) + "EmulatorLog=" + (mEmulatorLogEnabled ? "1" : "0")
		+ "\nStorageCard=" + mStorageCardWanted + "\n";
	if (!SDL_SaveFile(path.string().c_str(), text.data(), text.size()))
		mLog->FLogLine("Could not save the settings: %s", SDL_GetError());
}

/**
 \brief Insert or remove the NE2000 network card in slot 0, and remember the
 choice for the next launch.
 */
void TSDLApp::SetNetworkCardInserted(bool inInserted)
{
	if (!mPlatformManager) return;
	if (inInserted && !mNetworkCardInserted) {
		if (StorageSlot() == 0 && mStorageCard) {
			// eMate: one slot for both.
			RemoveStorageCard();
		}
		if (!mNetworkCard) mNetworkCard = new TNE2000Card();
		mPlatformManager->InsertPCCard(0, mNetworkCard);
	} else if (!inInserted && mNetworkCardInserted) {
		mPlatformManager->InsertPCCard(0, nullptr);
	}
	mNetworkCardInserted = inInserted;
	if (mNetworkCardWanted != inInserted) {
		mNetworkCardWanted = inInserted;
		SaveSettings();
	}
	mLog->FLogLine("Network card %s", inInserted ? "inserted" : "removed");
}

